-- ==================== GoCook 食材营养种子数据 ====================
-- 用途：供投稿/编辑菜谱时按食材清单自动计算营养（每 100g 含量）。
-- 数据来源：公开食物成分数据（中国食物成分表/USDA 等）的常用近似值，
--           仅供学习/演示用途，数值以 1 位小数近似，不构成医疗建议。
-- 执行方式（幂等，可重复执行；已存在行按规范名同步修订，无需手工 DELETE）：
--   docker exec -i gocook-postgres psql -U gocook -d gocookdb < ./seed_ingredient_nutrition.sql
-- 开发库一键重置（推荐入口）：bash ../reset_db.sh —— 本文件为第 2 步，见 sql/README.md
-- 约定：
--   · 本表为系统数据，重跑种子 = 全量同步修订（ON CONFLICT DO UPDATE），
--     营养库修正/扩充可随重跑自动应用到已灌入的库。
--   · default_portion_g：单个计数的近似质量（克），NULL 表示该食材无法按"个/只/根"换算，
--     投稿中若用这类计数单位且无单重，则该食材不参与营养计算。
--     部分蔬菜/肉类单重为常见规格近似（如西兰花 250g/颗、鸡胸肉 200g/块、生菜 40g/片）。
--   · 容器单位（杯/碗/勺/汤匙/茶匙）由服务端按固定容量近似换算（杯≈240ml、碗≈200ml、
--     汤匙≈15ml、勺≈10ml、茶匙≈5ml，1ml≈1g），不依赖本表单重。
--   · 干品（木耳/香菇/银耳等）按干重计；泡发后热量约为干品的 1/5~1/10。
--   · 调味料（盐/酱油/豆瓣酱等）钠含量显著，按实际用量计入。
--   · 规范名不含括号：投稿输入的名称会先去掉中英文括号括注（如"羊肉(瘦)"→"羊肉"），
--     带括号的规范名永远无法被命中（"瘦羊肉"直接以规范名收录）。
--   · 全量同步：执行时先清空旧行再插入（改名/废弃的规范名随之清除），
--     营养表是系统数据，不建议手工改行；重跑即恢复到与脚本一致的 200 行。
\set ON_ERROR_STOP on

-- 旧库升级：表可能尚不存在（新库已由 create_all_tables.sql 创建）；幂等，可安全重复执行
CREATE TABLE IF NOT EXISTS ingredient_nutrition (
    id SERIAL PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,                       -- 规范名（如"鸡蛋"）
    aliases TEXT[] NOT NULL DEFAULT '{}',            -- 别名（如"土鸡蛋"），匹配用
    default_portion_g DOUBLE PRECISION,              -- 单个计数的近似质量（克）；NULL=无法按个数换算
    calories DOUBLE PRECISION NOT NULL,              -- 热量（千卡 / 100g）
    protein_g DOUBLE PRECISION NOT NULL,             -- 蛋白质（克 / 100g）
    fat_g DOUBLE PRECISION NOT NULL,                 -- 脂肪（克 / 100g）
    carbs_g DOUBLE PRECISION NOT NULL,               -- 碳水化合物（克 / 100g）
    fiber_g DOUBLE PRECISION NOT NULL DEFAULT 0,     -- 膳食纤维（克 / 100g）
    sodium_mg DOUBLE PRECISION NOT NULL DEFAULT 0,   -- 钠（毫克 / 100g）
    vitamin_c_mg DOUBLE PRECISION NOT NULL DEFAULT 0,-- 维生素 C（毫克 / 100g）
    source TEXT NOT NULL DEFAULT '近似值，来自公开食物成分数据（中国食物成分表/USDA），仅供参考'
);
CREATE INDEX IF NOT EXISTS idx_ingredient_nutrition_name ON ingredient_nutrition (name);

